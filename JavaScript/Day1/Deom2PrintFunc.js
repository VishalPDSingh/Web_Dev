// ===============================
// Built-in Function: console.log()
// ===============================

// console.log() is a built-in JavaScript function.
// It prints (displays) data to the console/output screen.

// Printing numbers
console.log(10);          // Output: 10

// Printing strings
console.log("Hello World"); // Output: Hello World

// Printing variables
let age = 10;
console.log(age);         // Output: 10

// Printing multiple values
// Multiple values are separated by commas.
// They are printed on the same line with a space between them.

console.log(10, "Vishal", age, 'a', 34.5);

// Output:
// 10 Vishal 10 a 34.5

// Multiple console.log() statements print on separate lines.

console.log("Java");
console.log("Script");

// Output:
// Java
// Script